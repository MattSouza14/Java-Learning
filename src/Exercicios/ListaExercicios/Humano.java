package Exercicios.ListaExercicios;

public class Humano {
    protected String nome;
    protected String sexo;
    protected int idade;
    protected String lingua;
    protected String etnia;

    public Humano(String nome, String sexo, int idade, String lingua, String etnia) {
        this.nome = nome;
        this.sexo = sexo;
        this.idade = idade;
        this.lingua = lingua;
        this.etnia = etnia;
    }
}
